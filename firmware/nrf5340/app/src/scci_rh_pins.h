/* Logical carrier mapping, not a wiring instruction for an unmodified DK.
 * P0.00/.01 retain LFXO. P0.02/.03 require NFCT disabled in the overlay/UICR.
 * Four additional 165s serialize ACTUAL active Q and health, not candidate data. */
