"""Finite native FreeCAD GUI visibility/palette pass; run through the MCP bridge.

Only this package's two documents are saved. Existing unrelated documents are
not changed. Exported geometry is not regenerated by styling.
"""
from pathlib import Path
import json
import sys
import FreeCAD as App
import FreeCADGui as Gui
from pivy import coin

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import scci_rh_future_features


def style():
    rows = []
    for filename, exploded in [('SCCI_RH_future_interface.FCStd', False),
                               ('SCCI_RH_future_interface_exploded.FCStd', True)]:
        path = HERE/filename
        existing = [d for d in App.listDocuments().values()
                    if d.FileName and Path(d.FileName).resolve() == path.resolve()]
        doc = existing[0] if existing else App.openDocument(str(path))
        App.setActiveDocument(doc.Name)
        visible = []
        for obj in doc.Objects:
            if obj.TypeId == 'App::DocumentObjectGroup':
                obj.Visibility = True
                continue
            if 'Shape' not in obj.PropertiesList:
                continue
            physical = 'Category' in obj.PropertiesList and obj.Category == 'physical'
            show = bool(exploded or physical)
            obj.Visibility = show
            if show:
                visible.append(obj.Name)
            if 'DisplayColor' in obj.PropertiesList:
                obj.ViewObject.ShapeColor = tuple(obj.DisplayColor)[:3]
            obj.ViewObject.LineColor = (.10, .13, .17)
            obj.ViewObject.DisplayMode = 'Flat Lines'
            obj.ViewObject.LineWidth = .6
            if exploded and 'Allocation' in obj.Name:
                obj.ViewObject.Transparency = 65
        view = Gui.activeDocument().activeView()
        view.viewAxonometric(); view.fitAll()
        # The exported image aspect differs from a narrow desktop viewport.
        # Reserve margin so the exploded can and paddle tips stay in frame.
        camera = view.getCameraNode()
        if hasattr(camera, 'height'):
            camera.height.setValue(camera.height.getValue()*1.4)
        Gui.activeDocument().activeView().redraw()
        # A headless-generated document can open with FreeCAD's internal
        # read-only flag despite a writable file. Explicit saveAs to our own
        # existing package path saves the GUI view state reliably.
        doc.saveAs(str(path))
        image = HERE/('future-exploded-native.png' if exploded else 'future-fitted-native.png')
        view.saveImage(str(image), 1800, 1100, 'White')
        rows.append({'file': filename, 'visible_shape_count': len(visible),
                     'visible_objects': visible, 'native_application': 'FreeCAD '+'.'.join(App.Version()[:3]),
                     'view': 'axonometric', 'image': image.name})
    (HERE/'native-visual-receipt.json').write_text(json.dumps({'documents': rows}, indent=2)+'\n', encoding='utf-8')
    return rows


if __name__ == '__main__':
    print(json.dumps(style()))
