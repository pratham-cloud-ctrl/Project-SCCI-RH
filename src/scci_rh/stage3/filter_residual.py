"""Bound missing-input contamination in a declared digital SOS filter.

The reference is the SAME filter driven by an unknown, range-bounded digital
input at omitted apertures. This does not reconstruct analog neural signals,
bound an amplifier's physical recovery, or establish that clipping preserves
information. The state-space realization is extracted from sosfilt itself.
"""
import numpy as np
from scipy.signal import sosfilt


class FilterResidualBound:
    def __init__(self, sos, streams):
        self.sos = np.asarray(sos, dtype=float)
        if self.sos.ndim != 2 or self.sos.shape[1] != 6 or not np.all(np.isfinite(self.sos)):
            raise ValueError("finite SOS coefficients required")
        if not isinstance(streams, int) or streams < 1:
            raise ValueError("positive stream count required")
        self.streams = streams
        shape = (len(self.sos), 2)
        size = 2*len(self.sos)
        zero = np.zeros(shape)
        d, b = sosfilt(self.sos, [1.], zi=zero)
        a = np.zeros((size, size)); c = np.zeros(size)
        for k in range(size):
            initial = np.zeros(size); initial[k] = 1.
            output, final = sosfilt(self.sos, [0.], zi=initial.reshape(shape))
            a[:, k] = final.ravel(); c[k] = output[0]
        # First-order sections use padded SOS delays. Remove states that no
        # bounded input history can reach; their repeated zero poles otherwise
        # create a defective, nonminimal eigenbasis. A lost-history bound below
        # concerns states generated by this same filter's input, not arbitrary
        # corrupted memory contents.
        controllability = np.column_stack([np.linalg.matrix_power(a, k) @ b.ravel()
                                           for k in range(size)])
        vectors, singular, _ = np.linalg.svd(controllability)
        rank = int(np.sum(singular > singular[0]*1e-12))
        reachable = vectors[:, :rank]
        projection_residual = float(np.max(np.abs(a @ reachable-reachable @ (reachable.T @ a @ reachable))))
        a, b, c = reachable.T @ a @ reachable, reachable.T @ b.ravel(), c @ reachable
        size = rank
        poles, basis = np.linalg.eig(a)
        if np.max(np.abs(poles)) >= 1 or np.linalg.cond(basis) > 1e8:
            raise ValueError("stable, well-conditioned diagonalizable filter required")
        inverse = np.linalg.inv(basis)
        # Retain off-diagonal numerical residuals rather than assuming an exact
        # diagonalization. Elementwise magnitudes give a conservative modal
        # interval recurrence for all signs of omitted inputs.
        transition = np.abs(inverse @ a @ basis)
        self.transition = np.nextafter(transition, np.inf)
        self.input_gain = np.nextafter(np.abs(inverse @ b), np.inf)
        self.output_gain = np.nextafter(np.abs(c @ basis), np.inf)
        self.direct_gain = float(np.nextafter(abs(d[0]), np.inf))
        if np.max(np.abs(np.linalg.eigvals(self.transition))) >= 1:
            raise ValueError("modal magnitude bound must itself be stable")
        self.radius = np.zeros((size, streams))
        self.realization = {"state_dimension": size, "maximum_pole_magnitude": float(np.max(np.abs(poles))),
                            "basis_condition_number": float(np.linalg.cond(basis)),
                            "diagonalization_residual": float(np.max(np.abs(a @ basis-basis*poles))),
                            "reachable_projection_residual": projection_residual,
                            "floating_point_scope": "double-precision engineering bound with outward nextafter; not formal interval arithmetic"}

    def reset(self, *, prior_input_bound_v=0.):
        """Zero only at independent initialization; gaps use prior-input bound."""
        if not np.isfinite(prior_input_bound_v) or prior_input_bound_v < 0:
            raise ValueError("prior input bound must be finite and nonnegative")
        stationary = np.linalg.solve(np.eye(len(self.input_gain))-self.transition,
                                     self.input_gain*prior_input_bound_v)
        self.radius[:] = np.maximum(stationary, 0.)[:, None]

    def advance(self, omitted_input_bounds_v):
        bounds = np.asarray(omitted_input_bounds_v, dtype=float)
        if bounds.ndim != 2 or bounds.shape[1] != self.streams or not np.all(np.isfinite(bounds)) or np.any(bounds < 0):
            raise ValueError("finite nonnegative per-aperture input bounds required")
        out = np.empty_like(bounds)
        for k, bound in enumerate(bounds):
            out[k] = self.output_gain @ self.radius + self.direct_gain*bound
            self.radius = self.transition @ self.radius + self.input_gain[:, None]*bound
        return out
