"""Build the scoped Stage 3 mechanism report from saved digital evidence.

This is a revision report, not the project's final integrated manuscript.
All numerical studies have separate reproduction runners and receipts.
"""
from pathlib import Path
import hashlib
import json
from functools import partial

import matplotlib
from PIL import Image as PILImage
from reportlab.lib import colors
from reportlab.lib.styles import ParagraphStyle
from reportlab.pdfbase import pdfmetrics
from reportlab.pdfbase.ttfonts import TTFont
from reportlab.pdfgen.canvas import Canvas
from reportlab.platypus import (
    Image, PageBreak, Paragraph, SimpleDocTemplate, Spacer, Table, TableStyle,
)

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT/'output/pdf/SCCI_RH_stage3_mechanism_revision.pdf'
INK, BLUE, TEAL, GRAY = '#15293D', '#225B86', '#12756D', '#627485'
WIDTH = 475


def main():
    font = Path(matplotlib.get_data_path())/'fonts/ttf'
    for name, file in [('SCCIRH3', 'DejaVuSans.ttf'), ('SCCIRH3Bold', 'DejaVuSans-Bold.ttf')]:
        pdfmetrics.registerFont(TTFont(name, str(font/file)))
    pdfmetrics.registerFontFamily('SCCIRH3', normal='SCCIRH3', bold='SCCIRH3Bold', italic='SCCIRH3', boldItalic='SCCIRH3Bold')
    body = ParagraphStyle('body', fontName='SCCIRH3', fontSize=9.5, leading=14,
                          textColor=colors.HexColor(INK), spaceAfter=9)
    heading = ParagraphStyle('heading', parent=body, fontName='SCCIRH3Bold', fontSize=23, leading=29, spaceAfter=16)
    sub = ParagraphStyle('sub', parent=body, fontName='SCCIRH3Bold', fontSize=11.5, leading=16, spaceBefore=8)
    small = ParagraphStyle('small', parent=body, fontSize=8, leading=11.5, spaceAfter=7)
    label = ParagraphStyle('label', parent=small, fontName='SCCIRH3Bold', textColor=colors.HexColor(TEAL))
    story = []

    def p(text, style=body):
        story.append(Paragraph(text, style))

    def h(text):
        p(text, heading)

    def page():
        story.append(PageBreak())

    def image(path, width=WIDTH):
        with PILImage.open(ROOT/path) as im:
            w, height = im.size
        story.append(Image(str(ROOT/path), width=width, height=width*height/w))
        story.append(Spacer(1, 10))

    def table(rows, widths):
        tab = Table([[Paragraph(str(cell), small) for cell in row] for row in rows],
                    colWidths=widths, repeatRows=1, hAlign='LEFT')
        tab.setStyle(TableStyle([
            ('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#EAF0F5')),
            ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, colors.HexColor('#F6F9FB')]),
            ('VALIGN', (0, 0), (-1, -1), 'TOP'),
            ('LEFTPADDING', (0, 0), (-1, -1), 7), ('RIGHTPADDING', (0, 0), (-1, -1), 7),
            ('TOPPADDING', (0, 0), (-1, -1), 7), ('BOTTOMPADDING', (0, 0), (-1, -1), 7),
        ]))
        story.append(tab)
        story.append(Spacer(1, 10))

    p('PROJECT SCCI RH / MECHANISM REVISION S3-R2', label)
    h('From spinal observations\nto an admissible intervention')
    p('A digital evidence report for expert-informed practice and selected physiological feedback', sub)
    p('Pratham · Project SCCI RH · 12 October 2026', small)
    image('docs/stage1/figures/full-system.png')
    p('<b>Abstract.</b> Project SCCI RH proposes implanted spinal recording, computational interpretation, '
      'individualized stimulation and measured feedback. This revision tests intermediate requirements '
      'rather than presuming an ideal decoder or replaying expert voltages. New digital experiments '
      'separate teacher competence from reference fidelity, evaluate moving sources at contact apertures, '
      'validate causal forecasts, identify finite pulse responses, and derive prospective monitor precision. '
      'A connected reset-trial pilot withholds every intervention under the tested learner drift. '
      'Those failures define the next engineering choices.')
    p('<b>Evidence level.</b> All new measurements in this report are generated by declared artificial '
      'electrical/body/source models. No new human, animal or physical-device experiment is reported. '
      'Empirical allocations are finite model checks; they are not biological error guarantees.')
    p('AstroSam / Mind-Link inspires the progression from a future concept to inspectable engineering. '
      'The full native electronics, populated CAD and integrated final manuscript remain later work. '
      'This report covers selected Stage 3 revisions, not completion of the implant.', small)
    page()

    h('01 / Evidence becomes a design decision')
    p('The 28-page source paper is a research map. Its examples support individual mechanisms; '
      'the complete expert-spinal-recording → personalized intervention → retained learner benefit '
      'remains a conjunction to investigate. Primary reports [1–5] inform the controls below.')
    table([
        ['Experimental precedent', 'Design consequence', 'Limit retained'],
        ['El Hadwe et al. [1]: short-term circumferential spinal recordings; movement decoding in five rats',
         'Use a spatial contact model; compare neural features with measured movement; test sampling and ambiguity.',
         'Movement correlation is not an expert command. Offline bidirectional processing is not causal online decoding.'],
        ['McPherson et al. [2]: EMG-linked intraspinal stimulation during injured-rat retraining, with OFF follow-up',
         'Match practice exposure; distinguish assistance from retained performance; retain contingent and timing controls.',
         'Recovery with muscle triggering does not demonstrate expert neural transfer or doubled healthy learning speed.'],
        ['Nishimura et al. [3]: timing-dependent cortical-spike-triggered spinal stimulation in two monkeys',
         'Preserve processing, observation and onset delay; include nonbeneficial and harmful plasticity alternatives.',
         'A hybrid brain–spine mechanism supplies no universal spinal learning rule.'],
        ['Phillips et al. [4]: targeted lower-thoracic stimulation with measured pressure feedback after SCI',
         'Keep target-specific pressor authority, external pressure sensing, disturbances, saturation and fallback tests.',
         'No universal autonomic control, neural pressure decoder or healthy-user enhancement is established.'],
        ['Formento et al. [5]: stimulation can interfere with proprioceptive signaling',
         'Account for sensory cost and recording loss alongside immediate assistance.',
         'A constant synthetic sensory penalty is a hypothesis, not a fitted human dose law.'],
    ], [155, 160, 160])
    p('The wider platform vision retains bladder, cough, sensory and pelvic functions in the capability map. '
      'Each needs its own accessible pathways, state measurement, input directions and endpoint. '
      'Triggering a response alone does not establish selective delay or sustained control.', small)
    page()

    h('02 / Qualify what the teacher supplies')
    p('The new teacher revision generates sixteen complete 12-second recordings: two disclosed artificial '
      'performers, two cadences and four observation-noise realizations. Each generator supplies '
      '12 seconds for training and 84 seconds of withheld cadence/noise exposure. There is one '
      'artificial expert/contact geometry, not seven independent people.')
    table([
        ['Performer / cadence', 'Task competence', 'External reference', 'Neural reference'],
        ['Original voluntary / 1 Hz', '0 / 4', 'Unavailable', 'Unavailable'],
        ['Original voluntary / 1.15 Hz', '0 / 4', 'Unavailable', 'Unavailable'],
        ['Separate inverse-model / 1 Hz', '4 / 4', 'Finite-domain pass', 'Finite-domain pass'],
        ['Separate inverse-model / 1.15 Hz', '4 / 4', 'Unavailable', 'Unavailable'],
    ], [170, 85, 110, 110])
    p('Competence does not guarantee representation fidelity. The faster inverse performer passes '
      'the contact-peak task criteria, while its frozen template fails whole-trajectory allocation. '
      'The inverse generator uses a private body time constant to produce competence; the fitted '
      'library receives only measured contact features and external positions.')
    p('<b>Independent comparators.</b> An unavailable neural decoder must not disqualify a competent '
      'external teacher reference. External and neural alternatives use equal capture exposure. '
      'Neural fitting uses measured external labels, so incremental neural value still needs a '
      'matched comparison. The result is a task representation for learner-specific control, not '
      'expert memory or voltage transfer.')
    p('Moving sources at the actual contact apertures', sub)
    p('A separate 75-capture study evaluates the source at 4 kHz per contact with 3 microsecond '
      'contact skew. Six reference-grid comparisons retain paired noise and observation support. '
      'Holding moving source state for 5 ms fails 12 of 18 informative feature comparisons and '
      'six prediction comparisons under the fixed allocations. Dense-active neural packets '
      'remain unqualified. The fresh teacher captures therefore use actual apertures.')
    p('A deliberately ambiguous field produces identical contact features with conflicting measured '
      'positions. The observer must abstain in that declared construction. This is an observability '
      'witness, not proof that every biological spinal interface is ambiguous.', small)
    page()

    h('03 / A compact map of the revision')
    image('docs/stage3/figures/mechanism-revision.png')
    p('<b>Figure 1.</b> Four independent gates: teacher competence/reference availability, complete '
      'withheld forecast contexts, moving-source fidelity ratios and prospective delivery precision. '
      'A pass in one panel cannot replace a failed gate in another. The predictor keeps the '
      '15 mm threshold, including the narrow full-density failure.', small)
    table([
        ['Revision', 'Preserved evidence'],
        ['Teacher', 'Sixteen historical inputs remain unchanged; sixteen new aperture-resolved captures have separate identities.'],
        ['Source', '75 captures, 14,399,360 acquired contact samples and six grid pairs; absent/redundant controls remain distinct.'],
        ['Forecast', '31 fitted horizons and eight full withheld recordings; 248 recording/horizon checks, with four context passes and four rejects.'],
        ['Precision', 'Four observed calibrations, 144 requirement rows and 24 thresholds; current-monitor rejection is retained.'],
    ], [100, 375])
    page()

    h('04 / Predict without future measurements')
    p('The intervention-aware observer uses sixteen past external position samples, known task cues '
      'and a dose-history/declared-command grid. Complete monitor records become available after '
      'the 500 microsecond biphasic drive. Future measured charge, achieved movement, private '
      'activation, recruitment and skill coefficients are excluded from online inputs.')
    p('Four six-second predetermined command recordings train independent ridge models at every '
      '5 ms horizon from 0 through 150 ms. Chronological fitting is purged. Eight complete new '
      'recordings test every horizon without refitting failed contexts.')
    table([
        ['Complete withheld recording', 'Largest allocation', '15 mm gate'],
        ['Quarter density', '10.539 mm', 'Pass'], ['Half density', '12.175 mm', 'Pass'],
        ['Full density', '15.086 mm', 'Reject'], ['Unassisted', '8.925 mm', 'Pass'],
        ['Known 15% faster cadence', '79.689 mm', 'Reject'], ['Known 125 ms cue shift', '14.817 mm', 'Pass'],
        ['Changed response', '46.540 mm', 'Reject'], ['Unannounced 40 mm sensor offset', '51.571 mm', 'Reject'],
    ], [280, 110, 85])
    p('Runtime uncertainty remains live', sub)
    p('Let R be the larger saved training/context residual plus the 3 mm label allocation, '
      'P the current dose-interval projection, and A the saved total allocation. The live allowance '
      'is max(A<sub>train</sub>, A<sub>context</sub>, R + P). Enlarging a monitor interval can '
      'reject an unchanged mean prediction. Saved interval maxima are not added twice.')
    p('Predetermined recordings do not qualify arbitrary feedback commands. For a proposed action, '
      'use a zero-future-command baseline that retains ongoing past response, then add the new '
      'candidate response once. For gain G and dose u, include U<sub>G</sub>|u| + |G|U<sub>u</sub> '
      '+ U<sub>G</sub>U<sub>u</sub>, plus baseline and independent response residual allocations.')
    p('The current observer uses external learner measurements. Invalid spinal packets stay invalid; '
      'this result does not establish neural incremental value or retained learning.', small)
    page()

    h('05 / A pulse needs its own response model')
    p('The new dynamic experiment uses the unchanged electrical adapter for each nonzero pulse. '
      'The private body receives returned true charge; identification receives only completed '
      'independent monitor records and external measured positions. Twenty-four isolated signed '
      'calibration pulses are each paired with a separately measured resting baseline.')
    p('A 0–600 ms response table is fitted at 5 ms physical supports. Independent moving single, '
      'paired, repeated and changed-context trajectories are withheld. Integration at 2.5 ms '
      'and 0.625 ms is compared. Calibration gain intervals preserve the approximately 44.1% '
      'actual charge uncertainty; future 7.4% and 4% alternatives remain unqualified assumptions.')
    table([
        ['Response domain', 'Current monitor', 'Proposed future dose intervals'],
        ['Four moving single-route cases', 'Reject', 'Finite response-domain pass'],
        ['Two isolated paired-route cases', 'Reject', 'Finite response-domain pass'],
        ['Repeated and changed-context/fault cases', 'Reject', 'Reject'],
    ], [220, 100, 155])
    p('These admissions are response-component checks. Baseline error, reference availability, '
      'execution timing and online freshness still have to fit the complete correction gate. '
      'A continuous sparse policy cannot discard old pulse effects after 600 ms: no release '
      'rule beyond the measured response window has been qualified.')
    p('The biological transduction is explicitly reduced: charge-normalized drive is held for '
      'its 25 ms frame after a chosen 35 ms onset. The experiment identifies that surrogate; '
      'it does not prove how real spinal tissue responds to a 500 microsecond biphasic waveform.')
    p('The connected reset-trial pilot', sub)
    p('The new protocol allows at most one whole intervention per reset three-second trial. '
      'A declared washout premise separates trials while learned coefficients carry. Sixteen '
      'independent captures test four plasticity families at four starting coefficient scales. '
      'The common forecast context fails: its 150 ms allocation reaches 24.964 mm against '
      'the unchanged 15 mm limit. All 128 practice trials withhold stimulation; all 64 '
      'retention/transfer assessments stay OFF. No arm advantage or learning multiplier is shown.')
    p('Expert reference uncertainty comes from the maximum independent complete-trajectory '
      '2*RMSE, about 3.12 mm, rather than a training fit. Runtime qualification also binds '
      'the tested physical support and exact observed past pulse pattern. Passing a context '
      'name alone grants no authority beyond that evidence.', small)
    p('The delayed-residual guard checks targets only after their measurements arrive. Timed '
      'checks also expire missing observations when no later packet arrives. Cancellation '
      'stops continuation and cannot undo a delivered pulse.', small)
    page()

    h('06 / Turn model limits into requirements')
    p('Four fresh observed steady-response calibrations recover the current maps before varying '
      'prospective monitor uncertainty. The measured response floor remains fixed. No hidden '
      'recruitment matrix or threshold enters the requirement calculation.')
    table([
        ['Comparison allocation', 'Full single-route precision requirement', 'Meaning'],
        ['8 mm forecast input', '5.06–6.64% of nominal phase charge', 'A proposed 4% interval leaves scalar room in these calibrations.'],
        ['15 mm forecast input', '0.354–0.471% of nominal phase charge', 'Spending the forecast budget sharply tightens delivery precision.'],
        ['Two full simultaneous routes', 'Fails even at zero charge uncertainty', 'The 19 mm response floor plus forecast error already exceeds 25 mm.'],
    ], [115, 175, 185])
    p('These are steady effective-map requirements, not permission for fractional physical pulses '
      'or evidence that a new circuit has achieved the stated precision. The 8 mm forecast input '
      'is a comparison target; it is not a newly demonstrated assisted forecast. The dynamic '
      'single-frame study supplies a separate profile and response domain.')
    p('Detailed electronics must earn the allocation', sub)
    p('Investigate independently evidenced charge integration or edge capture. Bound both phases, '
      'gain and offset, bandwidth and intersample waveform error, integration-window edges, '
      'reset/hold behavior, correlated errors and simultaneous sources. A current threshold '
      'or increased nominal ADC rate is not a complete-waveform bound.')
    p('Stage 4 then implements native multichannel KiCad circuits, programmable routing, monitoring, '
      'power/telemetry and embedded timing. Stage 5 populates parametric CAD from actual boards, '
      'components, package and lead interfaces. Stage 2 allocation solids are preliminary '
      'resource models, not that completed assembly.')
    p('The pressure branch remains a second target-specific mechanism: external pressure feedback '
      'with identified positive pressor authority, disturbances and finite stop/hold/ramp '
      'fallbacks. Dense-stimulation neural recording remains unavailable in that model. '
      'It does not supply arbitrary pressure lowering or universal body automation.')
    page()

    h('07 / Inspect, reproduce and extend')
    p('The repository separates assumptions, observed synthetic records, qualification gates, '
      'proposals and biological unknowns. Historical results remain unchanged. Saved-evidence '
      'audits bind model sources and artifacts; separate runners recompute the experiments. '
      'The Git manifest binds committed blobs independently of checkout line endings.')
    table([
        ['Entry point', 'Purpose'],
        ['CURRENT_STATUS.md', 'Current stage, implemented scope and remaining integration.'],
        ['docs/stage3/README.md', 'Technical dossier and experiment-specific reproduction commands.'],
        ['scripts/verify_stage3_revision.py', 'Saved revision evidence, source identities and rejection-boundary audit.'],
        ['docs/stage3/isolated-pilot.md', 'Connected protocol, conservative drift rejection and pulse-free OFF results.'],
        ['docs/stage3/mechanism-to-electronics-handoff.md', 'Concrete detailed-design requirements and unresolved gates.'],
    ], [240, 235])
    p('Selected primary references', sub)
    refs = [
        ('[1] El Hadwe et al. (2026). Circumferential spinal recording and movement decoding.', 'https://www.nature.com/articles/s41467-026-75128-z'),
        ('[2] McPherson et al. (2015). Activity-dependent spinal stimulation during retraining.', 'https://pmc.ncbi.nlm.nih.gov/articles/PMC4593107/'),
        ('[3] Nishimura et al. (2013). Corticospinal plasticity with targeted stimulation.', 'https://depts.washington.edu/fetzweb/assets/nishimura_neuron.pdf'),
        ('[4] Phillips et al. (2025). Spinal stimulation for blood-pressure regulation.', 'https://www.nature.com/articles/s41591-025-03614-w'),
        ('[5] Formento et al. (2018). Proprioceptive consequences of spinal stimulation.', 'https://pmc.ncbi.nlm.nih.gov/articles/PMC6268129/'),
        ('AstroSam / Mind-Link: design-format inspiration.', 'https://github.com/sam-astro/Mind-link'),
    ]
    for text, url in refs:
        p(f'<link href="{url}" color="{BLUE}">{text}</link>', small)
    p('Reference descriptions are shortened topic labels. Cohorts, applicability and full source '
      'records are preserved in the Stage 1 audit and the evidence-to-design revision. The original '
      '28-page hypothesis paper remains read-only and is not an original experimental result.', small)
    p('<b>Contribution record.</b> Pratham defines the project ambition and scope. Codex/ChatGPT '
      'assists literature checking, modelling, implementation, review, figures and writing. '
      'Detailed decision and assistance records are in provenance/CONTRIBUTIONS.md. '
      'This report is an inspectable digital revision, not a claim of independent human efficacy.', small)

    def footer(canvas, doc):
        canvas.saveState()
        canvas.setStrokeColor(colors.HexColor('#D9E3EB'))
        canvas.line(60, 43, 535, 43)
        canvas.setFont('SCCIRH3', 7.5)
        canvas.setFillColor(colors.HexColor(GRAY))
        canvas.drawString(60, 28, 'PROJECT SCCI RH / STAGE 3 REVISION / DIGITAL MODEL EVIDENCE')
        canvas.drawRightString(535, 28, f'{doc.page} / 8')
        canvas.restoreState()

    OUT.parent.mkdir(parents=True, exist_ok=True)
    doc = SimpleDocTemplate(str(OUT), pagesize=(595.28, 841.89), leftMargin=60, rightMargin=60,
        topMargin=49, bottomMargin=58, title='Project SCCI RH - Stage 3 mechanism revision', author='Project SCCI RH / Pratham')
    doc.build(story, onFirstPage=footer, onLaterPages=footer, canvasmaker=partial(Canvas, invariant=1))
    print(json.dumps({'path': OUT.relative_to(ROOT).as_posix(), 'sha256': hashlib.sha256(OUT.read_bytes()).hexdigest()}))


if __name__ == '__main__':
    main()
